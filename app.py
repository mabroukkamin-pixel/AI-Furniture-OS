import streamlit as st

st.set_page_config(page_title="نظام الإدارة العالمي - أمين مبروك", layout="wide")

st.title("👑 النظام العالمي لإدارة العمليات")
st.write("نظام ثابت، جودة موحدة، وأداء احترافي بضغطة زر.")

# القائمة الرئيسية للأقسام
menu = st.sidebar.selectbox("اختر القسم:", ["إدارة التصميم", "إدارة الحسابات", "دليل حل المشكلات"])

if menu == "إدارة التصميم":
    st.header("إدارة التصميم (الجودة الموحدة)")
    template = st.selectbox("اختر نوع التصميم:", ["كتالوج أثاث", "كارت أعمال", "إعلان دهانات"])
    
    st.info("إرشادات إجبارية: يتم تطبيق إبعاد 1:1 تلقائياً، والألوان والخطوط معتمدة.")
    if st.button("توليد التصميم"):
        st.write(f"جاري تطبيق معايير الجودة لـ {template}...")
        st.success("تم إعداد التصميم مطابقاً للمواصفات الدولية.")

elif menu == "إدارة الحسابات":
    st.header("إدارة الحسابات (النظام المالي الصارم)")
    product = st.selectbox("اختر المنتج:", ["طرابيزة تلفزيون", "خزانة 4 رفوف"])
    price = {"طرابيزة تلفزيون": 60, "خزانة 4 رفوف": 85}
    st.write(f"السعر المعتمد: {price[product]} دينار")
    if st.button("إصدار فاتورة"):
        st.success("تم تسجيل الطلب وحساب التكلفة بدقة.")

elif menu == "دليل حل المشكلات":
    st.header("دليل الخطوات الصحيحة (أمين الافتراضي)")
    problem = st.selectbox("ما المشكلة التي تواجهها؟", ["اختلاف ألوان التصميم", "خطأ في السعر"])
    if problem == "اختلاف ألوان التصميم":
        st.error("الخطوة 1: لا تحاول تغيير الألوان يدوياً.")
        st.success("الخطوة 2: اطلب إعادة تحميل القالب الأصلي من النظام.")

st.sidebar.divider()
st.sidebar.write("إصدار النظام: 1.0 (إدارة القائد الأعلى)")
